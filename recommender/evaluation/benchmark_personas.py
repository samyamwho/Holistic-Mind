"""
Benchmark persona definitions for offline evaluation of the Holistic Mind recommender.
Contains 30 clinically representative scenarios spanning hyperarousal, hypoarousal,
cognitive fog, somatic tension, mindfulness, and safety/contraindication stress tests.
"""

from dataclasses import dataclass, field
from app.schemas import RecommendationContext
from evaluation.catalog import BENCHMARK_CATALOG


@dataclass
class BenchmarkPersona:
    id: str
    title: str
    category: str
    clinical_notes: str
    onboarding_goal: str
    check_in_answers: dict[str, str]
    journal_texts: list[str]
    relevance_scores: dict[str, int] = field(default_factory=dict)
    comfort_preferences: list[str] = field(default_factory=list)
    excluded_exercise_ids: list[str] = field(default_factory=list)
    contraindication_signals: list[str] = field(default_factory=list)

    def to_context(self) -> RecommendationContext:
        return RecommendationContext(
            user_id=f"benchmark_{self.id}",
            onboarding_goal=self.onboarding_goal,
            check_in_answers=self.check_in_answers,
            journal_texts=self.journal_texts,
            exercises=BENCHMARK_CATALOG,
            interactions=[],
            excluded_exercise_ids=self.excluded_exercise_ids,
            contraindication_signals=self.contraindication_signals,
            recent_recommendation_ids=[],
            limit=4,
        )


